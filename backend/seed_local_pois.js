async function seed() {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('Connected to MongoDB. Seeding verified local POIs...');

    // Upsert all local places
    let inserted = 0;
    for (const p of LOCAL_POIS) {
      p.lastSynced = new Date();
      await POI.findOneAndUpdate(
        { osmId: p.osmId },
        { $set: p },
        { upsert: true, new: true }
      );
      inserted++;
    }

    console.log(`✅ Successfully seeded ${inserted} authentic POIs around Krishnankovil / Srivilliputhur!`);
    process.exit(0);
  } catch (err) {
    console.error('Error seeding POIs:', err);
    process.exit(1);
  }
}

seed();
